"""Mock Younit client with SYNTHETIC EGX-style data.

Prices are generated by a seeded random walk so results are repeatable.
They are NOT real market data; tickers are real EGX names only so demos read
naturally. EGX trades Sunday to Thursday, so Fridays and Saturdays are skipped.
"""

from __future__ import annotations

import random
import uuid
from datetime import date, datetime, timedelta, timezone

from ..models import (
    Account,
    Bar,
    Order,
    OrderRequest,
    OrderStatus,
    OrderType,
    Position,
    Quote,
    Side,
)
from .base import BrokerClient

# ticker: (name, synthetic starting price in EGP, daily volatility)
UNIVERSE: dict[str, tuple[str, float, float]] = {
    "COMI": ("Commercial International Bank", 80.0, 0.018),
    "HRHO": ("EFG Holding", 22.0, 0.022),
    "TMGH": ("Talaat Moustafa Group", 55.0, 0.025),
    "EAST": ("Eastern Company", 27.0, 0.016),
    "SWDY": ("Elsewedy Electric", 70.0, 0.021),
    "FWRY": ("Fawry", 9.0, 0.028),
    "ETEL": ("Telecom Egypt", 40.0, 0.017),
    "ABUK": ("Abu Qir Fertilizers", 58.0, 0.020),
}

HISTORY_DAYS = 500  # calendar days of synthetic history
_ANCHOR = date(2026, 11, 1)  # fixed so data is identical across runs


def _is_trading_day(d: date) -> bool:
    return d.weekday() not in (4, 5)  # Fri=4, Sat=5


def _generate(symbol: str) -> list[Bar]:
    name, price, vol = UNIVERSE[symbol]
    rng = random.Random(f"younit-mock-{symbol}")
    bars: list[Bar] = []
    d = _ANCHOR - timedelta(days=HISTORY_DAYS)
    while d <= _ANCHOR:
        if _is_trading_day(d):
            ret = rng.gauss(0.0004, vol)
            open_ = price
            close = max(0.5, price * (1 + ret))
            high = max(open_, close) * (1 + abs(rng.gauss(0, vol / 3)))
            low = min(open_, close) * (1 - abs(rng.gauss(0, vol / 3)))
            bars.append(
                Bar(
                    day=d,
                    open=round(open_, 2),
                    high=round(high, 2),
                    low=round(low, 2),
                    close=round(close, 2),
                    volume=int(rng.uniform(2e5, 4e6)),
                )
            )
            price = close
        d += timedelta(days=1)
    return bars


class MockYounitClient(BrokerClient):
    name = "mock"

    def __init__(self, starting_cash: float = 100_000.0) -> None:
        self._bars = {s: _generate(s) for s in UNIVERSE}
        self._cash = starting_cash
        # A small starting portfolio so read-only tools have something to show.
        self._holdings: dict[str, tuple[int, float]] = {
            "COMI": (100, self._bars["COMI"][-60].close),
            "SWDY": (50, self._bars["SWDY"][-120].close),
            "FWRY": (400, self._bars["FWRY"][-30].close),
        }
        self._orders: dict[str, Order] = {}

    # helpers
    def _check(self, symbol: str) -> str:
        s = symbol.strip().upper()
        if s not in UNIVERSE:
            raise ValueError(f"Unknown symbol '{symbol}'. Try one of: {', '.join(UNIVERSE)}")
        return s

    def _last(self, symbol: str) -> float:
        return self._bars[symbol][-1].close

    # reads
    def get_account(self) -> Account:
        equity = self._cash + sum(q * self._last(s) for s, (q, _) in self._holdings.items())
        return Account(
            account_id="MOCK-0001",
            cash=round(self._cash, 2),
            equity=round(equity, 2),
            buying_power=round(self._cash, 2),
        )

    def get_positions(self) -> list[Position]:
        out = []
        for s, (qty, cost) in self._holdings.items():
            last = self._last(s)
            mv = qty * last
            pnl = qty * (last - cost)
            out.append(
                Position(
                    symbol=s,
                    quantity=qty,
                    avg_cost=round(cost, 2),
                    last_price=last,
                    market_value=round(mv, 2),
                    unrealized_pnl=round(pnl, 2),
                    unrealized_pnl_pct=round(100 * (last / cost - 1), 2),
                )
            )
        return out

    def list_symbols(self) -> dict[str, str]:
        return {s: v[0] for s, v in UNIVERSE.items()}

    def get_quote(self, symbol: str) -> Quote:
        s = self._check(symbol)
        last, prev = self._bars[s][-1], self._bars[s][-2]
        return Quote(
            symbol=s,
            name=UNIVERSE[s][0],
            last=last.close,
            change_pct=round(100 * (last.close / prev.close - 1), 2),
            volume=last.volume,
            as_of=datetime.combine(last.day, datetime.min.time(), tzinfo=timezone.utc),
        )

    def get_bars(self, symbol: str, start: date, end: date) -> list[Bar]:
        s = self._check(symbol)
        return [b for b in self._bars[s] if start <= b.day <= end]

    # writes (simulated fills at last close)
    def submit_order(self, request: OrderRequest) -> Order:
        s = self._check(request.symbol)
        price = self._last(s)
        order = Order(
            order_id=f"MOCK-{uuid.uuid4().hex[:8]}",
            request=request,
            status=OrderStatus.PENDING,
            created_at=datetime.now(timezone.utc),
        )
        fills_now = request.order_type == OrderType.MARKET or (
            request.order_type == OrderType.LIMIT
            and request.limit_price is not None
            and (
                (request.side == Side.BUY and price <= request.limit_price)
                or (request.side == Side.SELL and price >= request.limit_price)
            )
        )
        if fills_now:
            cost = price * request.quantity
            qty, avg = self._holdings.get(s, (0, 0.0))
            if request.side == Side.BUY:
                if cost > self._cash:
                    order.status = OrderStatus.REJECTED
                    self._orders[order.order_id] = order
                    return order
                self._cash -= cost
                new_qty = qty + request.quantity
                self._holdings[s] = (new_qty, (qty * avg + cost) / new_qty)
            else:
                if request.quantity > qty:
                    order.status = OrderStatus.REJECTED
                    self._orders[order.order_id] = order
                    return order
                self._cash += cost
                left = qty - request.quantity
                if left:
                    self._holdings[s] = (left, avg)
                else:
                    self._holdings.pop(s)
            order.status = OrderStatus.FILLED
            order.filled_price = price
        self._orders[order.order_id] = order
        return order

    def get_orders(self) -> list[Order]:
        return sorted(self._orders.values(), key=lambda o: o.created_at, reverse=True)

    def cancel_order(self, order_id: str) -> Order:
        order = self._orders.get(order_id)
        if order is None:
            raise ValueError(f"No order with id '{order_id}'.")
        if order.status != OrderStatus.PENDING:
            raise ValueError(f"Order {order_id} is {order.status.value} and cannot be cancelled.")
        order.status = OrderStatus.CANCELLED
        return order
